/**
 * `node scripts/check-features.ts` (`yarn features`): checks the feature catalogue (scripts/features/feature-check.ts)
 * and writes it, grouped, to features/catalogue.json and features/catalogue.md. Exit code 1 on errors. Part of
 * `yarn build`.
 *
 * `--list-ungrouped` prints, as JSON, the features that are in no group (input for the grouping agent) and exits.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { checkFeatures } from './features/feature-check.ts'
import type { Feature, FeatureCheckConfig, FeatureGroup, GroupsFile } from './features/feature-check.ts'
import { readSurfaces } from './features/surfaces.ts'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const config: FeatureCheckConfig = JSON.parse(readFileSync(join(root, 'features.config.json'), 'utf8'))
const groupsPath = join(root, config.groups)
const groupsFile: GroupsFile | undefined = existsSync(groupsPath) ? JSON.parse(readFileSync(groupsPath, 'utf8')) : undefined
const result = checkFeatures(root, config, readSurfaces(root, config), groupsFile)

if (process.argv.includes('--list-ungrouped')) {
  const ungrouped = result.features.filter(feature => !feature.group)
  console.log(JSON.stringify(ungrouped.map(({ parts, ...feature }) => feature), null, 2))
  process.exit(0)
}

for (const warning of result.warnings) {
  console.warn(`warning: ${warning}`)
}
for (const error of result.errors) {
  console.error(`error: ${error}`)
}

if (result.errors.length) {
  console.error(`\n✗ Feature catalogue: ${result.errors.length} error(s). Rules: AGENTS.md → "Feature catalogue".`)
  process.exit(1)
}

const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version
const byId = new Map(result.features.map(feature => [feature.id, feature]))
const groups = result.groups.map(group => ({ ...group, features: group.features.map(id => byId.get(id)!) }))

writeFileSync(join(root, config.catalogue), `${JSON.stringify({ version, groups }, null, 2)}\n`)
if (config.catalogueMarkdown) {
  writeFileSync(join(root, config.catalogueMarkdown), markdown(version, groups))
}
console.log(`✓ Feature catalogue: ${result.features.length} features in ${result.groups.length} groups, ${result.declarations.length} exports checked${result.warnings.length ? `, ${result.warnings.length} warning(s)` : ''}.`)

function markdown (appVersion: string, catalogue: Array<Omit<FeatureGroup, 'features'> & { features: Array<Feature> }>): string {
  const lines = [
    '<!-- Generated by `yarn features` from the @feature tags and features/groups.json. Do not edit. -->',
    '',
    `# Anita features (${appVersion})`,
    '',
    'What the app can do, grouped by what users want to achieve. Each group is the material of a guide; each feature',
    'lists what that guide must explain.',
    '',
  ]
  for (const group of catalogue) {
    lines.push(`- [${group.title}](#group-${group.id}) — ${group.features.length} features`)
  }
  for (const group of catalogue) {
    lines.push('', `## ${group.title}`, '', `<a id="group-${group.id}"></a>Group \`${group.id}\`. **Goal:** ${group.goal}`)
    if (group.audience) {
      lines.push('', `**Audience:** ${group.audience}`)
    }
    if (group.notes) {
      lines.push('', `**Notes for writers:** ${group.notes}`)
    }
    for (const feature of group.features) {
      lines.push('', `### ${feature.title}`, '', `\`${feature.id}\` · ${feature.status} · since ${feature.since} · \`${feature.source.file}:${feature.source.line}\``, '')
      lines.push(`${feature.summary}`, '')
      lines.push(`- **Where:** ${feature.where}`)
      lines.push(`- **How:** ${feature.usage}`)
      lines.push(`- **Options:** ${feature.options}`)
      lines.push(`- **Rules:** ${feature.rules}`)
      for (const [tag, items] of Object.entries(feature.surfaces)) {
        if (items.length) {
          lines.push(`- **${tag}:** ${items.map(item => `\`${item}\``).join(', ')}`)
        }
      }
      if (feature.related.length) {
        lines.push(`- **Related:** ${feature.related.map(id => `\`${id}\``).join(', ')}`)
      }
    }
  }
  return `${lines.join('\n').replace(/\n{3,}/g, '\n\n')}\n`
}
